export const resolveReviewProviders = ids => {
  if (new Set(ids).size !== ids.length) throw new Error('Duplicate review provider');
  return ids.map(id => {
    if (Object.hasOwn(providerNames, id)) return [providerNames[id], id];
    if (Object.hasOwn(textOnlyProviderNames, id)) return [textOnlyProviderNames[id], null];
    throw new Error(`Unknown review provider: ${id}`);
  });
};
