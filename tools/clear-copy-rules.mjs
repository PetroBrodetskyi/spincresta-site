  if (page === 'new-casinos/index.html' && /^Yes, if they hold valid licenses, use secure payments/.test(text)) return 'newSafety';
  if (page === 'top-rated/index.html' && /^Top rated sites offer realistic bonuses with fair wagering/.test(text)) return 'ratingBonus';
  if (/^online-casinos\/[^/]+\/index\.html$/.test(page) && /^Trusted reviews, licensed platforms, and exclusive offers for /.test(text)) return 'countryHeader';
  if (/^online-casinos\/[^/]+\/index\.html$/.test(page) && /\bimmersive (?:gameplay|live casino experiences|live dealer tables)\b/.test(text)) return 'removeImmersive';
  if (/were (?:visible|listed)\./.test(text) && /Pragmatic|Evolution|Hacksaw|Play.n GO/.test(text) && !/\d|not |licen|wager|limit/i.test(text)) return 'catalogPresent';
