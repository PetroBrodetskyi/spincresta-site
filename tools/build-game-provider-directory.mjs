import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { BRANDS } from '../scripts/brands.js';
import { getReviewProviders } from '../scripts/brand-review-providers.js';
import { providerNames } from '../scripts/provider-logo-library.js';
import { providerDirectoryKey } from '../scripts/provider-directory-key.js';
import { isPublishedBrandReview } from '../scripts/pages/brand-provider-strip.js';
import { siteIconMarkup } from '../scripts/site-icons.js';
import { escapeReview as esc } from './brand-review-template.mjs';
import { directoryCopy } from './game-provider-directory-copy.mjs';
import { gameExamples, providerSearchAliases } from './game-provider-directory-data.mjs';
import { syncDefaultTheme } from './sync-default-theme.mjs';

const origin = 'https://spincresta.com';
const locales = Object.keys(directoryCopy);
const date = '2026-11-24';
const check = process.argv.includes('--check');
const categories = ['slots', 'live', 'crash', 'table'];
const prefix = lang => lang === 'en' ? '/' : `/${lang}/`;
const directory = lang => prefix(lang) + 'game-providers/';
const review = (lang, slug) => prefix(lang) + 'brands/' + slug + '/';
const decode = value => value.replaceAll('&quot;', '"').replaceAll('&lt;', '<').replaceAll('&gt;', '>').replaceAll('&amp;', '&');
const fileFor = route => '.' + route + 'index.html';
const paged = new Map();
const active = (lang, slug) => {
  const path = fileFor(review(lang, slug));
  if (!paged.has(path)) {
    const html = existsSync(path) ? readFileSync(path, 'utf8') : '';
    paged.set(path, /<meta\b[^>]*name=["']robots["'][^>]*content=["'][^"']*noindex/i.test(html) ? '' : html);
  }
  return paged.get(path);
};
const save = (file, value) => {
  if (existsSync(file) && readFileSync(file, 'utf8') === value) return;
  if (check) {
    console.error('Stale provider directory output: ' + file);
    process.exitCode = 1;
    return;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, value);
};
const published = new Map(BRANDS.filter(brand => isPublishedBrandReview(brand) &&
  !brand.notRecommended && !brand.temporarilyUnavailable).map(brand => [brand.urlDetail.slice(7, -5), brand]));
const repeatedNames = new Set([...published.values()].map(({ name }) => name).filter((name, i, names) => names.indexOf(name) !== i));
const studios = new Map();
const aliases = new Map();
const getStudio = (name, logo) => {
  const canonical = providerNames[logo] || name;
  const key = providerDirectoryKey(canonical);
  if (!key) throw new Error('Missing provider key: ' + name);
  if (!studios.has(key)) studios.set(key, { key, name: canonical, logo, reviews: new Set(), games: [] });
  const studio = studios.get(key);
  studio.logo ||= logo;
  aliases.set(providerDirectoryKey(name), key);
  aliases.set(key, key);
  if (providerSearchAliases[canonical]) aliases.set(providerDirectoryKey(providerSearchAliases[canonical]), key);
  return studio;
};

for (const [slug] of published) {
  const html = active('en', slug);
  if (!html) continue;
  // Authored provider strips, such as ColdBet's, take precedence over the runtime fallback.
  const strip = html.match(/<ul\b[^>]*class="review-provider-strip"[^>]*>([\s\S]*?)<\/ul>/)?.[1];
  const names = strip ? [...strip.matchAll(/<li><span class="review-provider-logo">([\s\S]*?)<\/span><span>([^<]+)<\/span><\/li>/g)]
    .map(([, logo, name]) => [decode(name), logo.match(/\/images\/providers\/([a-z0-9-]+)\.svg/)?.[1] ?? null])
    : getReviewProviders(slug);
  for (const [name, logo] of names) getStudio(name, logo).reviews.add(slug);
}

for (const [name, title, category, slug] of gameExamples) {
  if (!published.has(slug) || !categories.includes(category) || !active('en', slug).includes(esc(title))) {
    throw new Error('Unverified provider example: ' + title + ' (' + slug + ')');
  }
  const studio = getStudio(name, null);
  studio.games.push({ title, category, slug });
  studio.reviews.add(slug);
}

const index = Object.fromEntries([...aliases].sort(([a], [b]) => a.localeCompare(b, 'en')));
save('scripts/provider-directory-index.js',
  '// Generated by tools/build-game-provider-directory.mjs.\n' +
  'export const providerDirectoryIndex = Object.freeze(' + JSON.stringify(index, null, 2) + ');\n');

const reviewLink = (lang, slug, regions) => {
  const { name, countries } = published.get(slug);
  const label = repeatedNames.has(name) && countries?.length === 1
    ? `${name} (${regions.of(countries[0])})` : name;
  return `<a class="provider-review-link" href="${esc(review(lang, slug))}">${esc(label)}</a>`;
};
const bodyPanel = (id, heading, content) => `<section class="account-panel" id="${id}" data-editorial-panel="${id}" aria-labelledby="${id}-title">
    <h2 id="${id}-title" tabindex="-1">${esc(heading)}</h2>
    ${content}
  </section>`;
const icon = name => siteIconMarkup(name, 'site-icon', 20);
const schema = (lang, c) => {
  const url = origin + directory(lang);
  return { '@context': 'https://schema.org', '@graph': [
    { '@type': 'CollectionPage', '@id': url + '#webpage', name: c.title, description: c.intro, url, inLanguage: lang,
      breadcrumb: { '@id': url + '#breadcrumb' } },
    { '@type': 'BreadcrumbList', '@id': url + '#breadcrumb', itemListElement: [
      { '@type': 'ListItem', position: 1, name: c.home, item: origin + prefix(lang) },
      { '@type': 'ListItem', position: 2, name: c.title, item: url },
    ] },
  ] };
};
const metaContent = (source, key, value) => {
  const re = new RegExp(`(<meta\\b(?=[^>]*\\b(?:property|name)="${key}")[^>]*\\bcontent=")[^"]*(")`, 'g');
  return source.replace(re, (_, before, after) => before + esc(value) + after);
};

for (const lang of locales) {
  const c = directoryCopy[lang];
  const templateFile = fileFor(prefix(lang) + 'payment-methods/');
  const template = readFileSync(templateFile, 'utf8');
  const regions = new Intl.DisplayNames(lang, { type: 'region' });
  const number = new Intl.NumberFormat(lang);
  const toReview = slug => reviewLink(lang, slug, regions);
  const catalog = [...studios.values()].map(studio => ({
    ...studio,
    reviews: [...studio.reviews].filter(slug => active(lang, slug)).sort((a, b) =>
      published.get(a).name.localeCompare(published.get(b).name, lang)),
    games: studio.games.filter(({ slug }) => active(lang, slug)),
  })).filter(studio => studio.reviews.length).sort((a, b) => a.name.localeCompare(b.name, lang, { numeric: true }));

  const rows = catalog.map(({ name, logo, key, reviews, games }) => {
    const kinds = [...new Set(games.map(game => game.category))];
    const search = [name, providerSearchAliases[name], ...games.map(({ title }) => title)].filter(Boolean).map(providerDirectoryKey).join(' ');
    const mark = logo ? `<img src="/images/providers/${esc(logo)}.svg" alt="" width="96" height="36" loading="lazy" decoding="async" />` : icon('layers');
    const examples = games.length ? `<p><strong>${esc(c.games)}:</strong> ${games.map(g => esc(g.title) + ' — ' + toReview(g.slug)).join(' · ')}</p>` : '';
    const reviewLinks = reviews.map(toReview).join(' · ');
    const count = number.format(reviews.length);
    const listed = `<p><strong>${esc(c.reviews)} (${count}):</strong> ${reviewLinks}</p>`;
    return `<li id="provider-${key}" data-provider-result data-provider-search="${esc(search)}" data-provider-types="${kinds.join(' ')}">
        <span class="review-provider-logo">${mark}</span>
        <div><h3>${esc(name)}</h3>${kinds.length ? `<p>${kinds.map(kind => esc(c[kind])).join(' · ')}</p>` : ''}${examples}${listed}</div>
      </li>`;
  }).join('\n      ');
  const controls = `<div data-provider-controls hidden>
      <div class="catalog-toolbar-row">
        <label class="catalog-search">${icon('search')}<input type="search" autocomplete="off" data-provider-query aria-label="${esc(c.search)}" placeholder="${esc(c.search)}" /></label>
        <div class="account-contact-fields provider-category-field"><label><span>${esc(c.filter)}</span><select data-provider-category>
          ${['all', ...categories].map(kind => `<option value="${kind}">${esc(c[kind])}</option>`).join('')}
        </select></label></div>
      </div>
      <p role="status">${esc(c.matches)} <span data-provider-count>${number.format(catalog.length)}</span></p>
    </div>
    <p data-provider-empty hidden>${esc(c.empty)}</p>`;
  const navItems = [['provider-directory', c.directory, 'layers'], ['provider-guide', c.guide, 'help']];
  const markup = `<main class="account-dashboard editorial-dashboard editorial-dashboard--payment-methods container" data-editorial-dashboard data-provider-directory>
      <header class="account-dashboard-heading">
        <h1 id="game-providers-heading">${esc(c.title)}</h1>
        <p>${esc(c.intro)}</p>
      </header>
      <div class="account-layout">
        <aside class="account-sidebar"><nav class="account-menu" aria-labelledby="game-providers-heading">
          ${navItems.map(([id, label, mark], i) => `<a href="#${id}" data-editorial-nav="${id}"${i === 0 ? ' aria-current="location"' : ''}>${icon(mark)}<span>${esc(label)}</span></a>`).join('\n          ')}
        </nav></aside>
        <div class="account-workspace">
          ${bodyPanel('provider-directory', c.directory, controls + '<p>' + esc(c.scope) + '</p>' +
            '<ul class="editorial-panel-rows" role="list">\n      ' + rows + '\n    </ul>')}
          ${bodyPanel('provider-guide', c.guide, `<div class="editorial-prose-sections"><section><h3>${esc(c.whatTitle)}</h3><p>${esc(c.what)}</p></section>
            <section><h3>${esc(c.scopeTitle)}</h3><p>${esc(c.scope)}</p></section></div>`)}
        </div>
      </div>
    </main>`;
  const title = c.title + ' | SpinCresta';
  let output = template
    .replace(/<title>[\s\S]*?<\/title>/, '<title>' + esc(title) + '</title>')
    .replace(/https:\/\/spincresta\.com\/(?:[a-z]{2}\/)?payment-methods\//g, value => value.replace('payment-methods/', 'game-providers/'))
    .replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>/, () =>
      '<script type="application/ld+json">' + JSON.stringify(schema(lang, c)).replaceAll('<', '\\u003c') + '</script>')
    .replace('class="payment-methods-page"', 'class="game-providers-page"')
    .replace(/<main\b[\s\S]*?<\/main>/, () => markup)
    .replace('</body>', '<script type="module" src="/scripts/pages/game-provider-directory.js?v=20261124-game-providers"></script>\n  </body>');
  for (const key of ['og:title', 'twitter:title']) output = metaContent(output, key, title);
  for (const key of ['description', 'og:description', 'twitter:description']) output = metaContent(output, key, c.intro);
  save(fileFor(directory(lang)), syncDefaultTheme(output).trimEnd() + '\n');
  if (lang === 'en') console.log(`Directory: ${catalog.length} providers, ${published.size} eligible review sources, ${gameExamples.length} documented game examples.`);
}

const urls = new Set(locales.map(lang => origin + directory(lang)));
const sitemap = readFileSync('sitemap.xml', 'utf8');
const current = sitemap.replace(/  <url>\n[\s\S]*?  <\/url>\n/g, block =>
  urls.has(block.match(/<loc>([^<]+)<\/loc>/)?.[1]) ? '' : block,
);
const entries = [...urls].map(url => `  <url>\n    <loc>${url}</loc>\n    <lastmod>${date}</lastmod>\n    <changefreq>monthly</changefreq>\n    <priority>0.6</priority>\n  </url>\n`).join('');
const nextEntry = current.includes('  <url>\n    <loc>' + origin + '/brands/bitgames/</loc>')
  ? '  <url>\n    <loc>' + origin + '/brands/bitgames/</loc>' : '</urlset>';
save('sitemap.xml', current.replace(nextEntry, entries + nextEntry));
