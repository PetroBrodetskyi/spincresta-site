#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { BRANDS } from '../scripts/brands.js';

const ROOT = process.cwd();
const LOCALES = ['de', 'es', 'it', 'pl', 'uk', 'pt', 'fr', 'hi'];

const decodeHtml = value =>
  value
    .replace(/&euro;/gi, '€')
    .replace(/&pound;/gi, '£')
    .replace(/&dollar;/gi, '$')
    .replace(/&amp;/gi, '&')
    .replace(/&quot;/gi, '"')
    .replace(/&apos;|&#39;/gi, "'")
    .replace(/&nbsp;/gi, ' ')
    .replace(/&#x([0-9a-f]+);/gi, (_, code) => String.fromCodePoint(Number.parseInt(code, 16)))
    .replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)))
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

const readBonusRows = locale => {
  const file = path.join(ROOT, locale ? locale : '', 'casinos-and-betting', 'index.html');
  const html = fs.readFileSync(file, 'utf8');
  return [...html.matchAll(/<article class="casino-list-row"[\s\S]*?<\/article>/g)].map(match => {
    const href = match[0].match(/href="(?:\/[a-z]{2})?\/brands\/([^"/]+)\/?"/)?.[1] || '';
    const paragraphs = [...match[0].matchAll(/<p class="casino-bonus">([\s\S]*?)<\/p>/g)];
    return {
      slug: href,
      bonus: paragraphs.length < 2 ? '' : decodeHtml(paragraphs[1][1].replace(/<strong>[\s\S]*?<\/strong>/, '')),
    };
  });
};

const english = readBonusRows('');
const translations = Object.fromEntries(LOCALES.map(locale => [locale, readBonusRows(locale)]));

for (const [locale, rows] of Object.entries(translations)) {
  if (rows.length !== english.length) {
    throw new Error(`${locale}: expected ${english.length} catalog rows, found ${rows.length}`);
  }
}

const output = Object.fromEntries(
  LOCALES.map(locale => {
    const localizedBySlug = new Map(translations[locale].map(row => [row.slug, row.bonus]));
    const entries = BRANDS.map(brand => {
      const source = brand.bonus?.replace(/\s+/g, ' ').trim();
      const slug = brand.urlDetail
        ?.replace(/^\/?brands\//, '')
        .replace(/\.html$/, '')
        .replace(/^\/+|\/+$/g, '');
      return [source, localizedBySlug.get(slug)];
    }).filter(([source, translated]) => source && translated);
    return [locale, Object.fromEntries(entries)];
  }),
);

const banner = '// Generated by tools/sync-brand-bonus-translations.mjs. Do not edit manually.\n';
const source = `${banner}export const BRAND_BONUS_TRANSLATIONS = ${JSON.stringify(output, null, 2)};\n`;
fs.writeFileSync(path.join(ROOT, 'scripts', 'brand-bonus-translations.js'), source);

console.log(`Brand bonus translations synced: ${english.length} catalog rows across ${LOCALES.length} locales.`);
