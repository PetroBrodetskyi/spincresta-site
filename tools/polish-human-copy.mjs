const localizedRoots = new Set(['de', 'es', 'it', 'pl', 'uk', 'pt', 'fr', '.git', 'node_modules', 'tools']);
const walkEnglish = directory => {
  const files = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (entry.isDirectory() && directory === ROOT && localizedRoots.has(entry.name)) continue;
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...walkEnglish(absolute));
    else if (entry.name === 'index.html') files.push(absolute);
  }
  return files;
};

for (const [locale, rules] of Object.entries(replacements)) {
  localeCounts[locale] = 0;
  const files = locale === 'en' ? walkEnglish(ROOT) : walk(path.join(ROOT, locale));
  for (const file of files) {
    const before = fs.readFileSync(file, 'utf8');
    let after = before;
    for (const [search, replacement] of rules) after = after.replaceAll(search, replacement);
    if (after === before) continue;
    fs.writeFileSync(file, after);
    changed += 1;
    localeCounts[locale] += 1;
  }
}

